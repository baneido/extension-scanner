#!/usr/bin/env node
// Regenerates the committed blocklist fallback snapshot from the authoritative
// chrome-mal-ids feed. The snapshot is a build-time-independent FLOOR: the
// shipped extension always carries a non-empty, validated, point-in-time
// blocklist so a fresh install with an unreachable source still has baseline
// coverage (Debt Map F-4). The production build never fetches this — it reads
// the committed file — so builds stay hermetic. Run via `npm run update-blocklist`.
//
// Exits non-zero (without writing) if the fetch/parse yields zero entries, so a
// broken upstream can never silently ship an empty snapshot.

import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
  "https://raw.githubusercontent.com/The-Privacy-Commons-Institute/chrome-mal-ids/refs/heads/master/data/current-list.json";

const OUT_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/data/blocklist-snapshot.generated.ts"
);

function parseIds(data) {
  if (typeof data !== "object" || data === null || !Array.isArray(data.extensions)) {
    throw new Error("Unexpected payload shape: expected { extensions: [...] }");
  }
  const ids = [];
  for (const entry of data.extensions) {
    if (typeof entry !== "object" || entry === null) continue;
    if (typeof entry.ext_id !== "string" || entry.ext_id.length === 0) continue;
    if (entry.browser === "edge") continue; // edge-only IOCs cannot match a Chrome install
    ids.push(entry.ext_id);
  }
  return [...new Set(ids)].sort();
}

async function main() {
  process.stdout.write(`Fetching ${SOURCE_URL}\n`);
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Fetch failed: HTTP ${res.status}`);
  const data = await res.json();

  const ids = parseIds(data);
  if (ids.length === 0) {
    throw new Error("Refusing to write an empty snapshot");
  }

  const generated = String(data?.meta?.generated ?? "unknown");
  const header = `// AUTO-GENERATED by scripts/update-blocklist-snapshot.mjs — do not edit by hand.
// Source: chrome-mal-ids (The Privacy Commons Institute), CC BY 4.0.
// Snapshot generated upstream at: ${generated}. ${ids.length} Chrome IOC IDs.
// This is a fallback FLOOR only; the live feed is the source of truth.
`;

  const body = `export const BLOCKLIST_SNAPSHOT_GENERATED = ${JSON.stringify(generated)};

export const BLOCKLIST_SNAPSHOT_IDS: readonly string[] = [
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
];
`;

  writeFileSync(OUT_PATH, header + "\n" + body);
  process.stdout.write(`Wrote ${ids.length} ids to ${OUT_PATH}\n`);
}

main().catch((err) => {
  process.stderr.write(`update-blocklist-snapshot failed: ${err?.message ?? err}\n`);
  process.exit(1);
});
